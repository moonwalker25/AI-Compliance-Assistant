# GENERATE CONVERSATION TITLE
# ============================================================

def generate_conversation_title(message):


    prompt = f"""
Generate a short natural title for this conversation.

User's first message:

{message}


Rules:

- Maximum 6 words.

- Describe the user's main topic.

- Do not use quotation marks.

- Do not include the words:
  Conversation
  Chat
  Query

- Do not use emojis.

- Return only the title.
"""


    response = ask_llm(
        SYSTEM_PROMPT,
        prompt
    )


    title = response.strip()


    if not title:
        return "New Conversation"


    return title[:80]