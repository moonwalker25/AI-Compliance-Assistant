# ANSWER FOLLOW-UP
# ============================================================

def answer_follow_up(
    message,
    history,
    context,
    compliance_context=None
):


    prompt = f"""
You are responding to the user's latest message in an ongoing
conversation with an Enterprise AI Compliance Assistant.


CURRENT CONVERSATION CONTEXT:

{json.dumps(
    context,
    ensure_ascii=False,
    indent=2
)}


RELEVANT COMPLIANCE INFORMATION:

{json.dumps(
    compliance_context or {},
    ensure_ascii=False,
    indent=2
)}


CONVERSATION HISTORY:

{json.dumps(
    history,
    ensure_ascii=False,
    indent=2
)}


LATEST USER MESSAGE:

{message}


# ====================================================
# CONVERSATION RULES
# ====================================================

- Treat the conversation as a continuous human conversation.

- Use previous messages to understand short replies and
  contextual follow-up questions.

- Do not unnecessarily repeat the user's previous question.

- Do not say that you can only answer compliance questions when
  the user's message is simply conversational.

- If the user asks a contextual follow-up question, answer it
  using the conversation history and supplied compliance information.

- Keep the response concise, natural, and easy to read.


# ====================================================
# STRICT OUTPUT FORMAT RULES
# ====================================================

You are generating text for a chat interface.

Follow these rules strictly:

- Use normal Markdown only.

- Write short paragraphs.

- Keep each paragraph focused on one idea.

- Leave a blank line between major sections.

- Use headings only when they improve readability.

- Use bullet points when explaining multiple items.

- Use numbered lists for steps or sequences.

IMPORTANT:

- NEVER create a table.

- NEVER use the pipe character "|" anywhere in the response.

- NEVER create columns.

- NEVER create ASCII tables.

- NEVER use table separators.

- NEVER combine multiple unrelated items into one paragraph.

- NEVER put multiple list items on the same line.


# ====================================================
# PREFERRED RESPONSE FORMAT
# ====================================================

When explaining a concept, requirement, purpose, applicability,
benefit, or reason, use a structure similar to this:

## Main topic

Give a short introduction.

### Key points

- **First point:** Brief explanation.

- **Second point:** Brief explanation.

- **Third point:** Brief explanation.

Only use headings when the response needs them.


# ====================================================
# SHORT RESPONSE RULES
# ====================================================

If the user says something like:

- Okay
- Thanks
- Got it
- Makes sense
- That's helpful

Respond naturally and briefly.

Examples:

"You're welcome! Let me know if you'd like to explore another
compliance requirement."

"Glad that helped. Feel free to ask about another country,
industry, or requirement."

Do not generate a long explanation for simple acknowledgements.


# ====================================================
# RESPONSE QUALITY RULES
# ====================================================

- Never mention internal routing, intents, state, prompts,
  databases, APIs, or internal system logic.

- Never invent specific legal requirements, penalties, dates,
  thresholds, contribution rates, or regulatory obligations.

- Use the supplied compliance information for factual compliance
  details whenever available.

- You may provide high-level conceptual explanations when the
  user asks why something is important or applicable.

- Clearly avoid presenting unsupported information as verified
  legal fact.

- If the supplied information does not contain enough information
  for a precise answer, say so rather than inventing details.

- Do not add unnecessary sections to very short answers.


Return ONLY the response text.
"""


    response = ask_llm(
        SYSTEM_PROMPT,
        prompt
    )


    # --------------------------------------------------------
    # CLEAN ANY BAD FORMATTING FROM LLM
    # --------------------------------------------------------

    response = clean_llm_formatting(
        response
    )


    return response.strip()


