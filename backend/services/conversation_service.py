# ============================================================
# CONVERSATION
# ============================================================

def get_or_create_conversation(
    session_id,
    db
):

    conversation = (
        db.query(Conversation)
        .filter(
            Conversation.id == session_id
        )
        .first()
    )

    if conversation:
        return conversation


    conversation = Conversation(
        id=session_id,
        title="New Conversation"
    )

    db.add(conversation)
    db.commit()
    db.refresh(conversation)

    return conversation


# ============================================================
# GET CONVERSATION HISTORY
# ============================================================

def get_conversation_history(
    session_id,
    db,
    limit=20
):

    messages = (
        db.query(ConversationMessage)
        .filter(
            ConversationMessage.conversation_id == session_id
        )
        .order_by(
            ConversationMessage.created_at.asc()
        )
        .limit(limit)
        .all()
    )


    return [
        {
            "role": message.sender,
            "content": message.message
        }
        for message in messages
    ]


# ============================================================
# SAVE MESSAGE
# ============================================================

def save_message(
    session_id,
    sender,
    message,
    db,
    message_data=None
):

    conversation = get_or_create_conversation(
        session_id,
        db
    )


    conversation_message = ConversationMessage(
        conversation_id=session_id,
        sender=sender,
        message=message,
        message_data=message_data
    )


    db.add(conversation_message)

    db.commit()
    db.refresh(conversation_message)


    return conversation_message


# ============================================================
# CLEAN BAD LLM FORMATTING
# ============================================================

def clean_llm_formatting(text: str) -> str:

    if not text:
        return ""


    # --------------------------------------------------------
    # NORMALIZE LINE BREAKS
    # --------------------------------------------------------

    text = text.replace("\r\n", "\n")
    text = text.replace("\r", "\n")


    # --------------------------------------------------------
    # REMOVE CODE BLOCK MARKERS
    # --------------------------------------------------------

    text = re.sub(
        r"```markdown",
        "",
        text,
        flags=re.IGNORECASE
    )

    text = text.replace(
        "```",
        ""
    )


    # --------------------------------------------------------
    # REMOVE TABLE SEPARATOR LINES
    #
    # Examples:
    #
    # | ----- | ----- |
    # |:----- | -----:|
    # --------------------------------------------------------

    text = re.sub(
        r"\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)+\|?",
        "",
        text
    )


    # --------------------------------------------------------
    # SPLIT PIPE-BASED CONTENT
    #
    # This handles malformed Markdown tables generated by the LLM.
    # --------------------------------------------------------

    lines = text.split("\n")

    cleaned_lines = []


    for line in lines:

        stripped = line.strip()


        # Skip completely empty lines temporarily
        if not stripped:

            cleaned_lines.append("")
            continue


        # ----------------------------------------------------
        # HANDLE PIPE CONTENT
        # ----------------------------------------------------

        if "|" in stripped:

            cells = [
                cell.strip()
                for cell in stripped.split("|")
                if cell.strip()
            ]


            # If multiple cells exist, convert them into
            # readable bullet points.
            if len(cells) >= 2:

                # Handle pairs nicely
                if len(cells) == 2:

                    cleaned_lines.append(
                        f"- **{cells[0]}:** {cells[1]}"
                    )

                else:

                    # Convert each cell into separate readable line
                    for cell in cells:

                        cleaned_lines.append(
                            f"- {cell}"
                        )

                continue


            # If only one useful cell remains
            elif len(cells) == 1:

                cleaned_lines.append(
                    cells[0]
                )

                continue


        # ----------------------------------------------------
        # NORMAL CONTENT
        # ----------------------------------------------------

        cleaned_lines.append(
            stripped
        )


    text = "\n".join(cleaned_lines)


    # --------------------------------------------------------
    # REMOVE EMPTY BULLETS
    # --------------------------------------------------------

    text = re.sub(
        r"(?m)^-\s*$",
        "",
        text
    )


    # --------------------------------------------------------
    # REMOVE EXCESSIVE BLANK LINES
    # --------------------------------------------------------

    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text
    )


    # --------------------------------------------------------
    # FIX BULLETS THAT ARE TOO CLOSE TOGETHER
    # --------------------------------------------------------

    text = re.sub(
        r"\n-\s+",
        "\n- ",
        text
    )


    return text.strip()


